SELECT * FROM [Calendar]

SELECT
	CAST(YEAR([Date]) AS NVARCHAR(4)) AS [Year]
FROM
	[Calendar]
WHERE
	YEAR([DATE]) BETWEEN 2014 AND YEAR(GETDATE())
GROUP BY
	YEAR([Date])
UNION
SELECT
	CAST(YEAR([Date]) AS NVARCHAR(4)) + '-' + CAST(YEAR([Date]) + 1 AS NVARCHAR(4))
FROM
	[Calendar]
WHERE
	YEAR([DATE]) BETWEEN 2014 AND YEAR(GETDATE()) - 1
GROUP BY
	YEAR([Date])
ORDER BY
	[Year]