	[OperationComplete]
FROM (
	SELECT
		ROW_NUMBER() OVER (
			PARTITION BY
				[ClkTransaction].[Operation]
			ORDER BY 
				ClkTransaction.LoggedOff DESC,
				ClkTransaction.TransactionID
		) AS [row_num],
		[ClkTransaction].[Operation],
		[EmployeeName],
		[OperationComplete],
		[WorkCentreCode]
	FROM
		[ClkTransaction]
	WHERE
		[ClkTransaction].[JobNumber] Like @WO
		AND [WorkCentreCode] LIKE '%S%'
	) AS [SrcTable]
