	[SrcA].[Serial Number],
	[SrcA].[Quote#],
	[SrcA].[WO#],
	[SrcA].[Model No],
	[COMPANY NAME],
	[SN] AS [Had SN Suffix First],
	[Src3].[Quote#],
	[Src3].[WO#],
	[Src3].[Model No]
FROM (
	SELECT 
		[Serial Number], [Quote#], [WO#], [Model No], [COMPANY NAME], [Special Instructions] 
	FROM 
		[Orders]
	INNER JOIN
		@t
	ON
		[Orders].[Serial Number] = [@t].[SN]
	INNER JOIN
		[Dealers]
	ON	
		[Orders].[DealerID] = [Dealers].[ID]
	WHERE
		[Special Instructions] IS NULL
		OR [Serial Number] IN (
			'2XBB6GY38RA000115',
			'2XBB2TP33RA000116',
			'2XBB6EY36RA000117',
			'2XBB2TP37RA000118'
		)
) AS [SrcA]
INNER JOIN
	@t AS [Src2]
ON
	RIGHT([SrcA].[Serial Number], 6) = RIGHT([Src2].[SN], 6)
INNER JOIN
	[Orders] AS [Src3]
ON
	[Src2].[SN] = [Src3].[Serial Number]
WHERE
	[SrcA].[Serial Number] <> [SN]

	ORDER BY
	CAST(RIGHT([SrcA].[Serial Number], 6) AS INT)